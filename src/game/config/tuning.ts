/**
 * 이동·카메라 튜닝 상수.
 *
 * 이 수치들이 곧 "트레일러 감성"의 정체다. TRAILER_FEATURE_ANALYSIS.md 3.3절이
 * 지적하듯 이동은 목적지 도달 수단이 아니라 놀이 그 자체이므로, 값을 코드에
 * 흩어두지 않고 한 곳에서 조율할 수 있어야 한다.
 *
 * 모든 속도 단위는 m/s, 가속도는 m/s^2, 각속도는 rad/s.
 */

/**
 * 탈것 종류.
 *
 * 거리에 세워져 있고, 가까이서 타면 그 조작감이 된다. 셋으로 나눈 기준은
 * 모양이 아니라 **손맛**이다 — 셋이 같은 수치를 쓰면 모델만 바뀐 것이고,
 * 그러면 굳이 셋일 이유가 없다.
 */
export type VehicleKind = "kickboard" | "bike" | "skateboard" | "toycar" | "pony" | "jetski";

/**
 * 탈것 목록.
 *
 * **순서가 곧 거치대의 번호(`cell`)다.** 거리에 세운 것과 화면에 그리는
 * 모양이 이 순서를 함께 쓰므로, 여기 순서를 바꾸면 킥보드 자리에 자전거가
 * 선다 — 검사가 두 곳을 대조한다.
 */
export const VEHICLE_KINDS: readonly VehicleKind[] = [
  "kickboard",
  "bike",
  "skateboard",
  "toycar",
  "pony",
  "jetski",
];

/**
 * 거리에 세워져 있는 탈것 — 공유 킥보드·자전거·장난감 자동차.
 *
 * 실제 한국 거리에서 인도 한쪽에 줄지어 서 있는 그것들이다. 가까이 가서
 * 타고, 내리면 두고 간다.
 */
export const STAND_VEHICLES: readonly VehicleKind[] = ["kickboard", "bike", "toycar"];

/**
 * 자연 구역에서 만나는 탈것 — 풀 뜯고 있는 조랑말.
 *
 * TRAILER_FEATURE_ANALYSIS 「3.3 이동 수단과 이동 능력」이 근거다. 트레일러에서
 * 아이가 타는 것은 도깨비가 아니라 **라마 비슷한 짐승**이고, 그건 기계 탈것이
 * 주지 못하는 것을 준다 — 살아 있고, 느리고, 걸음이 보인다.
 *
 * 라마를 그대로 옮기지 않는다. 우리 도시에 서 있을 법한 것은 제주 조랑말이다.
 *
 * 거치대(도시)와 자리를 나눈 것은 **자연 구역에서 탈 것이 사라지던 문제**와
 * 맞물린다. 인도가 없는 곳에는 거치대를 세울 기준선조차 없었다(`vehicleStands`
 * 주석). 풀밭에는 풀을 뜯는 것이 서 있으면 된다.
 */
export const PASTURE_VEHICLES: readonly VehicleKind[] = ["pony"];

/**
 * 물 위를 달릴 수 있는 것.
 *
 * 지금까지 **아무거나 타면 바다로 나갈 수 있었다**(`rideSurfaceHeight`가
 * 「타고 있는가」만 봤다). 조랑말이 수면 위를 걷고 자전거가 파도를 탔다 —
 * 바다에 나가는 방법을 만들면서 「탈것」을 한 덩어리로 본 결과다.
 *
 * 물에서만 값을 하는 것을 하나 두고, 나머지는 물가에서 멈춘다. 그래야
 * 부두까지 자전거로 달려와 갈아타는 동선이 생긴다.
 */
export const WATER_VEHICLES: readonly VehicleKind[] = ["jetski"];

/** 물 위를 달릴 수 있는가. 두 발이면 `null`이 들어온다 */
export function isWaterVehicle(kind: VehicleKind | LocomotionMode | null): boolean {
  return kind !== null && (WATER_VEHICLES as readonly string[]).includes(kind);
}

/**
 * 물가에 세워져 있는 탈것 — 제트스키.
 *
 * 거치대(인도)나 목장(풀밭)이 아니라 **부두 앞**이다. 거기 있어야 「바다로
 * 나가려면 저기로 간다」가 지도를 안 보고도 읽힌다.
 */
export const SHORE_VEHICLES: readonly VehicleKind[] = ["jetski"];

/**
 * 늘 들고 다니는 탈것.
 *
 * 거치대가 멀어도 이건 꺼낼 수 있다 — 없으면 빈 골목에서 탈 것 단추가 아무
 * 일도 안 하고, 그러면 조작표에 있는 키가 거짓말이 된다.
 */
export const CARRIED_VEHICLE: VehicleKind = "skateboard";

export type LocomotionMode = "walk" | "run" | VehicleKind;

/** 두 발로 가는 중인가, 무언가를 타고 있는가 */
export function isVehicle(mode: LocomotionMode): mode is VehicleKind {
  return mode !== "walk" && mode !== "run";
}

