/**
 * 시작 마당 — 첫 화면에 세우는 담과 그 앞의 스폰.
 *
 * 참고하는 트레일러 장면은 기와담장이 눈높이를 채우고 그 너머로 현대 건물이 서
 * 있는 골목이다. 시작 지점이 담 없는 상가 광장이라 첫 화면에 간판만 여덟 개가
 * 들어왔다. 광장 자리는 그대로 두고 **담만 가져온다.**
 *
 * 광장을 옛 마을로 옮기지 않는 이유는 자리다. 옛 마을 구역은 전부 지도 위쪽
 * 가장자리라 스폰을 그리로 보내면 시야의 절반이 월드 밖이 된다 —
 * `CITY.plazaBlockIndex` 주석에 적힌 그 사고다.
 *
 * `cityLayout`을 **값으로** import하지 않는다. 그쪽이 이 파일을 부르므로 순환이
 * 되고, 이 저장소는 그 순환 하나로 검사 49개가 죽는 걸 이미 겪었다(`zones.ts`
 * 주석). 구역 크기는 인자로 받는다.
 */

import { wallReach } from "@/game/world/oldTown";

/**
 * 시작 마당의 문턱 폭(m).
 *
 * 옛 마을 문턱(`WALL.doorway`, 5.2m)보다 넓다. 마을은 지나가는 곳이라 사람 하나
 * 지날 폭이면 되지만 여기는 시작 지점이라 **네 방향 모두가 출구**다.
 */
export const COURTYARD_DOORWAY = 12;

/**
 * 담을 세울 변 — 남북 두 변.
 *
 * **마주 보는 두 변이어야 한다.** 이웃한 두 변을 고르면 그 사이에 모서리가 생기고,
 * 목적지가 대각선일 때 거기 끼여 여정이 끝나지 않는다 — `playthrough` 검사 두 건이
 * 실제로 그렇게 죽었다. 문턱을 12m로 넓혀도 결과가 한 자리도 안 바뀌었으니 막은
 * 것은 변 가운데가 아니라 모서리였다. 마주 보는 변끼리는 만나지 않으므로 동서가
 * 통째로 트인 채 남는다.
 *
 * 한 변만 세워 봤더니 담이 화면 한쪽 끝에만 걸려 「담장 옆을 지나간다」로 보였다.
 * 높이로는 보강할 수 없다 — 기와 갓까지 1.67m인데 3인칭 카메라를 막는 선이 1.8m라
 * 여유가 13cm뿐이다(`oldTown`의 `COURSE.cap` 주석). 높이 대신 **변 수**로 채운다.
 */
export const COURTYARD_WALL_EDGES = [
  { dx: 0, dz: -1 },
  { dx: 0, dz: 1 },
] as const;

/**
 * 시작 지점을 북쪽 담에서 얼마나 띄울지(m).
 *
 * 구역 한복판에 세우면 담까지 15.8m다. 담은 1.67m뿐이라 그 거리에서는 화면
 * 아래쪽에 회색 띠로만 남고 화단 상자와 구분도 안 된다 — 담을 세워 놓고도 첫
 * 화면은 여전히 간판 밭이었다.
 *
 * 5m면 담이 눈높이를 채우면서 홍살문 전체가 화면에 들어온다. 더 붙이면 3인칭
 * 카메라가 담 뒤로 밀려 시작하자마자 시야가 막힌다.
 */
const COURTYARD_SPAWN_CLEARANCE = 5;

/**
 * 시작 지점 둘레에서 광장 화단을 비우는 반지름(m).
 *
 * 화단 고리는 구역 **중심**을 둘러싸도록 놓인다. 스폰을 담 앞으로 옮기자 그 고리의
 * 한 짝이 스폰 바로 옆에 섰고, 동쪽으로 3.7m 가서 막혔다(`terrainWalk` 검사가
 * 잡았다). 시작하자마자 막히는 자리는 없어야 한다.
 */
export const COURTYARD_SPAWN_CLEAR_RADIUS = 8;

/**
 * 시작 지점의 z. 북쪽 담 앞이다.
 *
 * 담 위치에서 빼서 구한다 — 좌표를 따로 적으면 `WALL.edgeInset`이나 구역 크기를
 * 고칠 때 한쪽만 움직여 스폰이 담을 뚫거나 멀어진다.
 */
export function courtyardSpawnZ(centerZ: number, blockSize: number): number {
  return centerZ - (wallReach(blockSize) - COURTYARD_SPAWN_CLEARANCE);
}
