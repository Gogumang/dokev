/**
 * 주민에게 말 걸기.
 *
 * PROJECT_PLAN의 핵심 루프는 「주민들과 대화하고」로 시작하는데, 지금까지
 * 군중은 걸어 다니기만 하고 말을 걸 수 없었다. 도시가 사람으로 차 있어도
 * 만질 수 없으면 배경화면과 같다.
 *
 * 대화는 한 줄이다. 분기도 선택지도 없다 — 여정과 경쟁하지 않으면서
 * 「이 동네에 사람이 산다」만 전하면 된다. 대사를 길게 만들면 달리다 멈춰
 * 읽어야 하고, 그러면 아무도 말을 걸지 않게 된다.
 *
 * 순수 함수로 둔다. 누가 가까운지·무슨 말을 하는지는 화면 없이 확인할 수 있다.
 */

/*
 * 말을 걸 수 있는 거리(m). 스쳐 지나가며 눌러도 걸릴 만큼은 넉넉해야 한다.
 *
 * 내보내지 않는다 — 판정은 `isWithinTalkRange`가 한다. 값을 밖으로 내면
 * 부르는 쪽마다 비교를 다시 쓰게 되고, 그러면 규칙이 갈라진다.
 */
const TALK_RADIUS = 3.4;

/** 한 줄이 화면에 머무는 시간(초) */
export const TALK_LINE_SECONDS = 4;

/**
 * 주민이 하는 말.
 *
 * 목록은 내보내지 않는다 — 누가 무슨 말을 하는지는 `residentLine`이 정한다.
 *
 * 도깨비도 여정도 언급하지 않는다. 주민은 이 소동을 모르는 사람들이고,
 * 그 온도 차가 도시를 살아 있게 만든다. 시간대나 장소를 특정하지도 않는다 —
 * 어디서 눌러도 어색하지 않아야 한다.
 */
const RESIDENT_LINES: readonly string[] = [
  "요즘 골목이 좀 시끄럽죠? 고양이인 줄 알았어요.",
  "저 위 간판, 어제까지 불이 안 들어왔는데.",
  "천천히 다녀요. 여기 자전거가 자주 지나가요.",
  "노을이 이 골목에 걸리는 시간이 제일 예뻐요.",
  "자판기 커피가 생각보다 괜찮아요.",
  "짐이 무거워 보이네요. 어디까지 가요?",
  "그 보드, 여기서 타면 잘 나가요. 턱만 조심하고.",
  "오늘 바람이 좋네요.",
];

/**
 * 주민 하나가 늘 같은 말을 하도록 고른다.
 *
 * 누를 때마다 무작위로 뽑으면 같은 사람이 매번 다른 말을 해서 사람이 아니라
 * 자판기처럼 느껴진다. 번호로 정하면 「아까 그 사람」이 성립한다.
 */
export function residentLine(index: number): string {
  // 음수·소수가 들어와도 목록 밖으로 나가지 않는다
  const safe = Math.abs(Math.floor(index));
  return RESIDENT_LINES[safe % RESIDENT_LINES.length];
}

/**
 * 말을 걸 수 있는 거리인가.
 *
 * 방향은 보지 않는다. 등 뒤 사람에게 말을 걸어도 이상하지 않고, 각도까지
 * 맞추게 하면 왜 안 걸리는지 알 수 없어 그냥 안 누르게 된다.
 */
export function isWithinTalkRange(distanceSquared: number): boolean {
  return distanceSquared <= TALK_RADIUS * TALK_RADIUS;
}
