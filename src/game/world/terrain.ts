/**
 * 지형 고저차 — 순수 함수.
 *
 * 도시가 y=0 평면 한 장이었다. 색과 간판이 아무리 촘촘해도 **길이 평평하면
 * 지도처럼 보인다** — 언덕을 오르내릴 때 생기는 시야 변화(마루 너머가 안
 * 보이다가 한 번에 펼쳐지는 것)가 없으면 도시의 깊이가 사라진다. 참고하는
 * 트레일러에서 동네가 살아 있는 느낌의 큰 몫이 이 오르내림이다.
 *
 * 노이즈 텍스처나 하이트맵 이미지를 쓰지 않는다(에셋 없음 원칙). 사인 몇 개를
 * 겹쳐 만든다 — 값이 연속이고 미분도 연속이라 걸을 때 턱이 생기지 않고,
 * 어디서든 O(1)로 즉시 구할 수 있어 배치·물리·렌더가 같은 식을 공유한다.
 *
 * 스폰 광장도 평평하게 두지 않는다. 한동안 광장 둘레를 눌러 평지로 만들었는데,
 * 그 「누른 자리 → 비탈」 이음매가 완만하려면 반경이 넓어야 하고, 결국 **시작
 * 지점 반경 57m가 통째로 평지**가 됐다. 안개가 60m부터 시작하니 처음 보이는
 * 범위가 전부 평지였다 — 언덕을 넣고도 첫 화면은 예전 그대로였다. 광장이
 * 조금 기울어 보이는 쪽이, 도시가 평평해 보이는 것보다 낫다.
 *
 * three를 모른다. 배치 데이터도, 렌더도, 플레이어 이동도 여기서 높이를 받는다.
 */

/**
 * 언덕 높이(m).
 *
 * 도시 한 변이 282m다. 5m는 100m를 걸어 5% 남짓 오르는 정도 — 서울의
 * 평범한 언덕 동네가 이 정도다. 더 키우면 도로가 롤러코스터가 되고, 무엇보다
 * 축 정렬 상자인 건물이 비탈에 박혀 한쪽이 뜬다.
 */
const HILL_HEIGHT = 5.6;

/**
 * 언덕 하나의 폭(m).
 *
 * 도시 한 변(282m)에 마루가 서너 개 들어가는 크기다. 더 짧으면 블록마다
 * 오르내려 멀미가 나고, 더 길면 화면 안에서는 그냥 기울어진 평면이다.
 */
const HILL_SPAN = 88;

/** 두 번째 겹 — 첫 겹과 나란히 놓이지 않게 파장을 어긋나게 둔다 */
const RIPPLE_HEIGHT = 1.8;
const RIPPLE_SPAN = 41;

/**
 * 세 번째 겹 — 블록 하나 정도 길이의 잔물결.
 *
 * 큰 언덕만 있으면 **한 블록 안에서는 여전히 평평하다.** 골목을 걷는 동안
 * 눈에 들어오는 오르내림은 이 짧은 겹이 만든다. 낮게 둬야 한다 — 키우면
 * 길이 물결치듯 출렁여 멀미가 난다.
 */
const ROLL_HEIGHT = 0.55;
const ROLL_SPAN = 17;

/**
 * 그 지점의 지면 높이(m).
 *
 * **이 함수가 지형의 정본이다.** 배치·충돌·렌더가 각자 다른 식을 쓰면 건물이
 * 공중에 뜨거나 발이 땅에 묻힌다 — 화면에서만 보이고 코드로는 안 보이는
 * 종류의 어긋남이다.
 */
export function terrainHeight(x: number, z: number): number {
  const hill = Math.sin(x / HILL_SPAN) * Math.cos(z / (HILL_SPAN * 0.82)) * HILL_HEIGHT;
  const ripple = Math.sin((x + z * 0.6) / RIPPLE_SPAN) * RIPPLE_HEIGHT;
  const roll = Math.sin((x * 0.7 - z) / ROLL_SPAN) * ROLL_HEIGHT;

  return hill + ripple + roll;
}

/**
 * 수면 높이(m).
 *
 * 지형 함수와 같은 파일에 둔다. **이 값과 지형의 최저점(-7.95m)의 관계가
 * 화면을 정한다** — 조금만 아래로 두면 경계에서 땅이 낮은 자리는 물이 발치까지
 * 차오르고(모래밭) 마루인 자리는 16m 벼랑이 된다. 한 값으로 해변과 절벽이
 * 같이 나온다.
 *
 * 더 내리면 어디서나 높은 벼랑이라 물이 멀어지고, **올려서 지형 최저점을 넘기면
 * 도시 안쪽 골짜기가 잠긴다.** 검사가 그 관계를 지킨다.
 */
export const SEA_LEVEL = -8.6;
